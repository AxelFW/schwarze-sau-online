#!/usr/bin/env node
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
import { Worker, isMainThread, parentPort, workerData } from 'worker_threads';
import {
  RL_FEATURE_NAMES,
  makeInitialRlModel,
  normalizeRlModel,
} from '../shared/game/rlBot.js';
import { RL_POLICY } from '../shared/game/rlPolicyData.js';
import { makeSeededRng } from '../shared/game/cards.js';
import {
  buildOneRlVsHeuristicPolicies,
  isSeatWinner,
  parseArgs,
  relativeSeatMargin,
  runSimulatedMatch,
} from './rl-sim.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

const randn = rng => {
  const u = Math.max(1e-12, rng());
  const v = Math.max(1e-12, rng());
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
};

const meanVectors = vectors => {
  const out = Array.from({ length: vectors[0]?.length ?? 0 }, () => 0);
  for (const vector of vectors) {
    for (let i = 0; i < out.length; i++) out[i] += vector[i] || 0;
  }
  return out.map(x => x / Math.max(1, vectors.length));
};

const clampWeights = weights => weights.map(w => Math.max(-8, Math.min(8, Number(w) || 0)));

const evaluateWeights = (weights, {
  seed,
  matches,
  rounds,
  exploration = 0,
  candidateMode = 'legal',
}) => {
  const model = {
    ...makeInitialRlModel({ candidateMode }),
    weights,
    metadata: { source: 'training-evaluation' },
  };
  const margins = [];
  let wins = 0;
  let failures = 0;

  for (let m = 0; m < matches; m++) {
    const rlSeat = m % 4;
    try {
      const match = runSimulatedMatch({
        rounds,
        seed: seed + m * 9973,
        policies: buildOneRlVsHeuristicPolicies(model, rlSeat, { exploration }),
      });
      margins.push(relativeSeatMargin(match.scores, rlSeat));
      if (isSeatWinner(match.scores, rlSeat)) wins += 1;
    } catch (_error) {
      failures += 1;
      margins.push(-1000);
    }
  }

  const avgMargin = margins.reduce((sum, x) => sum + x, 0) / Math.max(1, margins.length);
  return {
    fitness: avgMargin - failures * 100,
    avgMargin,
    winRate: wins / Math.max(1, matches),
    failures,
  };
};

const splitIntoChunks = (items, chunkCount) => {
  const chunks = Array.from({ length: chunkCount }, () => []);
  for (let i = 0; i < items.length; i++) chunks[i % chunkCount].push(items[i]);
  return chunks.filter(chunk => chunk.length);
};

const evaluateCandidateChunk = (chunk, options) =>
  chunk.map(candidate => ({
    ...candidate,
    result: evaluateWeights(candidate.weights, {
      seed: options.evalSeed,
      matches: options.matches,
      rounds: options.rounds,
      candidateMode: options.candidateMode,
      exploration: options.exploration ?? 0,
    }),
  }));

const evaluatePopulation = async (candidates, options) => {
  const workers = Math.max(1, Math.min(Number(options.workers || 1), candidates.length));
  if (workers <= 1) return evaluateCandidateChunk(candidates, options);

  const chunks = splitIntoChunks(candidates, workers);
  const workerUrl = new URL(import.meta.url);
  const batches = await Promise.all(chunks.map((chunk, workerIndex) => new Promise((resolve, reject) => {
    const worker = new Worker(workerUrl, {
      workerData: {
        mode: 'evaluatePopulationChunk',
        chunk,
        options,
        workerIndex,
      },
    });
    worker.on('message', message => {
      if (message?.ok) resolve(message.evaluated);
      else reject(new Error(message?.error || 'RL worker failed.'));
    });
    worker.on('error', reject);
    worker.on('exit', code => {
      if (code !== 0) reject(new Error(`RL worker exited with code ${code}.`));
    });
  })));

  return batches.flat();
};

if (!isMainThread) {
  try {
    if (workerData?.mode !== 'evaluatePopulationChunk') {
      throw new Error('Unknown RL worker mode.');
    }
    const evaluated = evaluateCandidateChunk(workerData.chunk, workerData.options);
    parentPort.postMessage({ ok: true, evaluated });
  } catch (error) {
    parentPort.postMessage({ ok: false, error: error?.message || String(error) });
  }
}

const writePolicyData = (model, trainingSummary) => {
  const policyPath = path.join(rootDir, 'shared/game/rlPolicyData.js');
  const roundedModel = {
    ...model,
    weights: model.weights.map(w => Number(w.toFixed(8))),
    metadata: {
      ...(model.metadata ?? {}),
      trainingSummary,
    },
  };
  const body = `// Generated by scripts/train-rl-residual.mjs. Do not edit by hand.\n` +
    `export const RL_POLICY = Object.freeze(${JSON.stringify(roundedModel, null, 2)});\n`;
  fs.writeFileSync(policyPath, body);

  const metricsPath = path.join(rootDir, 'shared/game/rlPolicyTraining.json');
  fs.writeFileSync(metricsPath, JSON.stringify(roundedModel.metadata, null, 2) + '\n');
};

const main = async () => {
  const args = parseArgs(process.argv);
  const availableWorkers = typeof os.availableParallelism === 'function'
    ? os.availableParallelism()
    : os.cpus().length;
  const generations = Number(args.get('generations') ?? 12);
  const population = Number(args.get('population') ?? 24);
  const eliteCount = Number(args.get('elite') ?? Math.max(3, Math.floor(population * 0.25)));
  const matches = Number(args.get('matches') ?? 40);
  const rounds = Number(args.get('rounds') ?? 8);
  const seed = Number(args.get('seed') ?? 20260703);
  const sigmaInitial = Number(args.get('sigma') ?? 0.55);
  const sigmaDecay = Number(args.get('sigma-decay') ?? 0.88);
  const resumeCurrent = Boolean(args.get('resume-current'));
  const currentModel = resumeCurrent ? normalizeRlModel(RL_POLICY) : null;
  const candidateModeArg = args.get('candidate-mode');
  const candidateMode = String(candidateModeArg ?? currentModel?.candidateMode ?? 'legal') === 'heuristic' ? 'heuristic' : 'legal';
  const validationMatches = Number(args.get('validation-matches') ?? Math.max(80, matches * 2));
  const validationSeed = Number(args.get('validation-seed') ?? seed + 999000);
  const workers = Math.max(1, Math.min(Number(args.get('workers') ?? availableWorkers), population));
  const shouldWrite = !args.get('no-write');

  let mean = currentModel?.weights?.length === RL_FEATURE_NAMES.length
    ? [...currentModel.weights]
    : makeInitialRlModel({ candidateMode }).weights;
  let sigma = sigmaInitial;
  let best = {
    weights: [...mean],
    train: evaluateWeights(mean, { seed, matches, rounds, candidateMode }),
    generation: 0,
  };

  console.log(JSON.stringify({
    event: 'start',
    generations,
    population,
    eliteCount,
    matches,
    rounds,
    seed,
    sigmaInitial,
    candidateMode,
    workers,
    writePolicy: shouldWrite,
    resumeCurrent,
    availableWorkers,
    featureCount: RL_FEATURE_NAMES.length,
  }, null, 2));

  for (let generation = 1; generation <= generations; generation++) {
    const rng = makeSeededRng(seed + generation * 100003);
    const candidates = [{ weights: [...mean], source: 'mean', index: 0 }];
    while (candidates.length < population) {
      candidates.push({
        source: 'sample',
        index: candidates.length,
        weights: clampWeights(mean.map(w => w + randn(rng) * sigma)),
      });
    }

    const evalSeed = seed + generation * 50021;
    const evaluated = (await evaluatePopulation(candidates, {
      evalSeed,
      matches,
      rounds,
      candidateMode,
      workers,
    })).sort((a, b) => b.result.fitness - a.result.fitness);

    const elites = evaluated.slice(0, eliteCount);
    mean = clampWeights(meanVectors(elites.map(x => x.weights)));
    sigma *= sigmaDecay;

    if (evaluated[0].result.fitness > best.train.fitness) {
      best = {
        weights: [...evaluated[0].weights],
        train: evaluated[0].result,
        generation,
      };
    }

    console.log(JSON.stringify({
      event: 'generation',
      generation,
      sigma: Number(sigma.toFixed(4)),
      bestThisGeneration: evaluated[0].result,
      bestOverall: {
        generation: best.generation,
        train: best.train,
      },
    }));
  }

  const trainedModel = normalizeRlModel({
    kind: 'residual-linear-card-policy',
    version: 1,
    trained: true,
    candidateMode,
    featureNames: [...RL_FEATURE_NAMES],
    weights: best.weights,
    metadata: {
      source: 'cross-entropy-simulation-training',
      trainedAt: new Date().toISOString(),
    },
  });

  const validation = evaluateWeights(trainedModel.weights, {
    seed: validationSeed,
    matches: validationMatches,
    rounds,
    candidateMode,
  });

  const trainingSummary = {
    algorithm: 'parallel cross-entropy residual policy search',
    generations,
    population,
    eliteCount,
    matchesPerCandidate: matches,
    roundsPerMatch: rounds,
    seed,
    validationSeed,
    validationMatches,
    candidateMode,
    workers,
    bestGeneration: best.generation,
    train: best.train,
    validation,
  };

  if (shouldWrite) {
    writePolicyData({
      ...trainedModel,
      metadata: {
        ...trainedModel.metadata,
        trainedAt: new Date().toISOString(),
      },
    }, trainingSummary);
  }

  console.log(JSON.stringify({
    event: 'complete',
    wrotePolicy: shouldWrite,
    trainingSummary,
  }, null, 2));
};

if (isMainThread) {
  main().catch(error => {
    console.error(error);
    process.exit(1);
  });
}
